// Export real Express-rendered PUG/EJS HTML as a static GitHub Pages preview.
// GitHub Pages cannot run Express, CRUD endpoints, or server-side sessions.
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import { server } from '../src/server.mjs'

const OUTPUT = resolve(process.cwd(), '.pages-dist')
const BASE_PATH = (process.env.PAGES_BASE_PATH ?? '/express-homework-03-pug-ejs').replace(/\/$/, '')
const ORIGIN = 'http://127.0.0.1:3000'

// The source server listens on port 3000 and must be stopped before exporting.
async function ready() {
  if (server.listening) return
  await new Promise((ok, fail) => {
    server.once('listening', ok)
    server.once('error', fail)
  })
}

async function get(path, accept) {
  const response = await fetch(`${ORIGIN}${path}`, { headers: { Accept: accept } })
  if (!response.ok) throw new Error(`${path}: expected 200, got ${response.status}`)
  return response
}

function rewriteLinks(html) {
  // The Express templates contain root-relative links. Rewrite them for the
  // GitHub Pages subdirectory and give HTML routes trailing / for index.html.
  return html.replace(/\bhref="\/(users|articles|assets)([^\"]*)"/g, (_match, section, rest) => {
    const local = `/${section}${rest}`
    if (section === 'assets') return `href="${BASE_PATH}${local}"`
    const route = local.replace(/\/$/, '')
    return `href="${BASE_PATH}${route}/"`
  })
}

const banner = `<aside class="preview-banner" aria-label="Preview information">
  <strong>Static preview</strong>
  <span>HTML generated by the actual Express application at build time. API changes and sessions require local Node.js.</span>
</aside>`

function prepareHtml(html) {
  if (!html.includes('<main')) throw new Error('Expected semantic <main> in rendered page')
  const revised = rewriteLinks(html).replace(/(<main\b[^>]*>)/, `$1\n${banner}`)
  if (!revised.includes('preview-banner')) throw new Error('Preview disclaimer missing')
  if (/\bhref="\/(?:users|articles|assets)(?:\/|\")/.test(revised)) {
    throw new Error('Unrewritten root-relative project links found')
  }
  return revised.replaceAll('Each page is rendered from live server-side data.',
    'This static page was generated from server-side data at build time.')
}

async function writePage(relative, html) {
  const path = join(OUTPUT, relative, 'index.html')
  await mkdir(resolve(path, '..'), { recursive: true })
  await writeFile(path, prepareHtml(html), 'utf8')
}

function safeId(id) {
  if (typeof id !== 'string' || !/^[a-zA-Z0-9_-]+$/.test(id)) {
    throw new Error(`Refusing unsafe export path: ${JSON.stringify(id)}`)
  }
  return id
}

