let exitCode = 0
try {
  await ready()
  await rm(OUTPUT, { recursive: true, force: true })
  await mkdir(OUTPUT, { recursive: true })
  await cp(resolve('src/public'), join(OUTPUT, 'assets'), { recursive: true })

  const cssPath = join(OUTPUT, 'assets/css/styles.css')
  await writeFile(cssPath, (await readFile(cssPath, 'utf8')) + demoCss, 'utf8')
  await writeFile(join(OUTPUT, 'index.html'), landing(), 'utf8')

  const users = await (await get('/users', 'application/json')).json()
  const articles = await (await get('/articles', 'application/json')).json()
  if (!Array.isArray(users) || !Array.isArray(articles)) {
    throw new Error('Expected JSON arrays from both REST collection endpoints')
  }

  await writePage('users', await (await get('/users', 'text/html')).text())
  await writePage('articles', await (await get('/articles', 'text/html')).text())
  for (const user of users) {
    const id = safeId(user.id)
    await writePage(`users/${id}`, await (await get(`/users/${id}`, 'text/html')).text())
  }
  for (const article of articles) {
    const id = safeId(article.id)
    await writePage(`articles/${id}`, await (await get(`/articles/${id}`, 'text/html')).text())
  }

  console.log(`OK: Exported ${2 + users.length + articles.length} Express-rendered PUG/EJS HTML pages`)
  console.log(`OK: .pages-dist/index.html, assets, and link rewriting for ${BASE_PATH || '/'}`)
  console.log('NOTE: Public preview is static. REST writes and sessions require a running Express server.')
} catch (err) {
  exitCode = 1
  console.error('Static preview export failed:', err)
} finally {
  await new Promise((done) => server.close(() => done()))
}
process.exitCode = exitCode
